// Helper to construct rectangle points and bbox
function makeRect(x: number, y: number, w: number, h: number): {
  points: [number, number][];
  center: [number, number];
  bbox: { x: number; y: number; width: number; height: number };
} {
  return {
    points: [
      [x, y],
      [x + w, y],
      [x + w, y + h],
      [x, y + h],
    ],
    center: [x + w / 2, y + h / 2],
    bbox: { x, y, width: w, height: h },
  };
}

// Helper to construct polygon points and bbox from arbitrary vertices
export function makePoly(pts: [number, number][]): {
  points: [number, number][];
  center: [number, number];
  bbox: { x: number; y: number; width: number; height: number };
} {
  const xs = pts.map(p => p[0]);
  const ys = pts.map(p => p[1]);
  const minX = Math.min(...xs);
  const maxX = Math.max(...xs);
  const minY = Math.min(...ys);
  const maxY = Math.max(...ys);
  
  // Polygon centroid
  let cx = 0;
  let cy = 0;
  pts.forEach(([x, y]) => {
    cx += x;
    cy += y;
  });
  cx /= pts.length;
  cy /= pts.length;

  return {
    points: pts,
    center: [Math.round(cx * 10) / 10, Math.round(cy * 10) / 10],
    bbox: {
      x: minX,
      y: minY,
      width: maxX - minX,
      height: maxY - minY,
    },
  };
}

