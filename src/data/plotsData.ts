// Helper to convert polygon points to SVG path 'd' string
export function pointsToPath(pts: [number, number][]): string {
  if (!pts.length) return '';
  return `M ${pts[0][0]} ${pts[0][1]} ` + pts.slice(1).map(p => `L ${p[0]} ${p[1]}`).join(' ') + ' Z';
}

